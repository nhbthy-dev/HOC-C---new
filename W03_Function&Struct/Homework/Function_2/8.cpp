/*Bảng số giảm dần
Viết hàm reverse_number_square để tạo một bảng số vuông kích thước n × n.

Các số được sắp xếp từ n * n giảm dần đến 1, theo thứ tự từ trái sang phải và từ trên xuống dưới.

Ví dụ với n = 3:

9 8 7
6 5 4
3 2 1
Quy ước chuỗi kết quả:

Các số trên cùng một dòng cách nhau đúng một khoảng trắng.
Các dòng cách nhau bằng ký tự xuống dòng \n.
Không có ký tự xuống dòng dư ở cuối chuỗi.
Sinh viên cần tự định nghĩa đầy đủ hàm dựa trên prototype sau:

string reverse_number_square(int n);
For example:

Input	
3
Result
9 8 7
6 5 4
3 2 1

*/