/*Bảng số tăng dần
Viết hàm number_square để tạo một bảng số vuông kích thước n × n.

Các số được sắp xếp lần lượt từ 1đến n * n, theo thứ tự từ trái sang phải và từ trên xuống dưới.

Ví dụ với n = 3:

1 2 3
4 5 6
7 8 9
Quy ước chuỗi kết quả:

Các số trên cùng một dòng cách nhau đúng một khoảng trắng.
Các dòng cách nhau bằng ký tự xuống dòng \n.
Không có ký tự xuống dòng dư ở cuối chuỗi.
Sinh viên cần tự định nghĩa đầy đủ hàm dựa trên prototype sau:

string number_square(int n);
For example:

Input	
3
Result
1 2 3
4 5 6
7 8 9

*/