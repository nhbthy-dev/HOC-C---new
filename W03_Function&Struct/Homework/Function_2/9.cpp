/*Bảng số ziczac theo dòng
Viết hàm zigzag_number_square để tạo một bảng số vuông kích thước n × n.

Các giá trị từ 1 đến n * n được sắp xếp theo từng dòng:

Dòng lẻ: các giá trị tăng từ trái sang phải.
Dòng chẵn: các giá trị giảm từ trái sang phải.
Đánh số dòng bắt đầu từ 1.

Ví dụ với n = 3:

1 2 3
6 5 4
7 8 9
Quy ước chuỗi kết quả:

Các số trên cùng một dòng cách nhau đúng một khoảng trắng.
Các dòng cách nhau bằng ký tự xuống dòng \n.
Không có ký tự xuống dòng dư ở cuối chuỗi.
Sinh viên cần tự định nghĩa đầy đủ hàm dựa trên prototype sau:

string zigzag_number_square(int n);
For example:

Input	
3
Result
1 2 3
6 5 4
7 8 9

*/