/*Kiểm tra số hoàn hảo
Viết hàm check_perfect_number để kiểm tra số nguyên dương n có phải là số hoàn hảo hay không.

Một số hoàn hảo là số có tổng các ước dương của nó, không tính chính nó, bằng đúng giá trị của số đó.

Ví dụ:

6 = 1 + 2 + 3
Hàm trả về:

1 nếu n là số hoàn hảo.
0 nếu n không phải là số hoàn hảo.
Sinh viên cần tự định nghĩa đầy đủ hàm dựa trên prototype sau:

int check_perfect_number(int n);
For example:

Input	Result
6       1

*/